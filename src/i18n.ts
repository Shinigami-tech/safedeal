/** Interface languages. Keys are the English strings; {name} placeholders are filled by t(). */

export type Lang = 'en' | 'ru' | 'kk';
export const LANGS: { id: Lang; label: string; ai: string }[] = [
  { id: 'en', label: 'EN', ai: 'English' },
  { id: 'ru', label: 'РУ', ai: 'Russian' },
  { id: 'kk', label: 'ҚАЗ', ai: 'Kazakh' },
];

const KEY = 'safedeal-lang';
export let lang: Lang = (() => {
  try {
    const v = localStorage.getItem(KEY);
    if (v === 'ru' || v === 'kk' || v === 'en') return v;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('ru') ? 'ru' : nav.startsWith('kk') ? 'kk' : 'en';
})();

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l;
}

export const aiLang = () => LANGS.find((l) => l.id === lang)!.ai;

